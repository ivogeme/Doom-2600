; =============================================================================
; DOOM 2600 - PROTÓTIPO FALSO-3D
; Atari 2600 / 6507
; DASM
;
; Recursos:
;   - Mapa 8x8
;   - Jogador X/Y
;   - Direção 0-3
;   - Movimento com colisão
;   - Rotação
;   - Raycast simplificado
;   - Parede em perspectiva
;   - Tiro + áudio
;   - Frame NTSC de 262 linhas
;
; Direções:
;   0 = Norte
;   1 = Leste
;   2 = Sul
;   3 = Oeste
;
; Mapa:
;   1 = parede
;   0 = espaço livre
; =============================================================================

    processor 6502

    include "vcs.h"
    include "macro.h"


; =============================================================================
; RAM DO ATARI 2600
; =============================================================================

    SEG.U variables
    ORG $80

PosX:           .byte
PosY:           .byte
Dir:            .byte

TempX:          .byte
TempY:          .byte
Temp:           .byte

RayDist:        .byte
WallFound:      .byte
RayStepCount:   .byte

LineCounter:    .byte
TopLine:        .byte
BottomLine:     .byte

SoundTimer:     .byte


; =============================================================================
; ROM
; =============================================================================

    SEG code
    ORG $F000


; =============================================================================
; RESET
; =============================================================================

Start:

    SEI
    CLD

    LDX #$FF
    TXS

    ; -------------------------------------------------------------------------
    ; Limpa RAM
    ; -------------------------------------------------------------------------

    LDA #0
    LDX #$FF

ClearLoop:

    STA 0,X
    DEX
    BNE ClearLoop


    ; -------------------------------------------------------------------------
    ; Limpa TIA
    ; -------------------------------------------------------------------------

    LDA #0

    STA VSYNC
    STA VBLANK

    STA PF0
    STA PF1
    STA PF2

    STA GRP0
    STA GRP1

    STA ENAM0
    STA ENAM1
    STA ENABL

    STA AUDV0
    STA AUDV1

    ; -------------------------------------------------------------------------
    ; Configuração do playfield
    ; -------------------------------------------------------------------------

    LDA #%00000001
    STA CTRLPF


    ; -------------------------------------------------------------------------
    ; Cores iniciais
    ; -------------------------------------------------------------------------

    LDA #$00
    STA COLUBK

    LDA #$C2
    STA COLUP0

    LDA #$1C
    STA COLUP1

    LDA #$0E
    STA COLUPF


    ; -------------------------------------------------------------------------
    ; Estado inicial
    ; -------------------------------------------------------------------------

    LDA #1
    STA PosX

    LDA #1
    STA PosY

    LDA #0
    STA Dir

    STA SoundTimer


; =============================================================================
; LOOP PRINCIPAL
; =============================================================================

MainLoop:

    JSR FrameSync

    JSR CheckInput

    JSR UpdateAudio

    JSR RenderScene

    JMP MainLoop


; =============================================================================
; FRAME NTSC
;
; 3 linhas VSYNC
; 37 linhas VBLANK
; 192 linhas visíveis
; 30 linhas overscan
;
; Total = 262 linhas
; =============================================================================

FrameSync:

    ; -------------------------------------------------------------------------
    ; VSYNC
    ; -------------------------------------------------------------------------

    LDA #2
    STA VSYNC

    STA WSYNC
    STA WSYNC
    STA WSYNC

    LDA #0
    STA VSYNC


    ; -------------------------------------------------------------------------
    ; VBLANK
    ;
    ; Mantemos VBLANK ligado enquanto executamos a lógica do jogo.
    ; -------------------------------------------------------------------------

    LDA #2
    STA VBLANK

    LDX #37

VBlankLoop:

    STA WSYNC

    DEX
    BNE VBlankLoop

    RTS


; =============================================================================
; INPUT
;
; Atari 2600 / Joystick Player 0:
;
; SWCHA:
;   bit 7 = cima
;   bit 6 = baixo
;   bit 5 = esquerda
;   bit 4 = direita
;
; INPT4:
;   botão de tiro do Player 0
; =============================================================================

CheckInput:

    ; -------------------------------------------------------------------------
    ; Direita
    ; -------------------------------------------------------------------------

    LDA SWCHA
    AND #%00010000

    BNE CheckLeft

    JSR TurnRight
    RTS


CheckLeft:

    LDA SWCHA
    AND #%00100000

    BNE CheckForward

    JSR TurnLeft
    RTS


CheckForward:

    LDA SWCHA
    AND #%10000000

    BNE CheckFire

    JSR MoveForward
    RTS


CheckFire:

    LDA INPT4

    BMI NoFire

    JSR FireWeapon


NoFire:

    RTS


; =============================================================================
; ROTAÇÃO DIREITA
; =============================================================================

TurnRight:

    LDA Dir

    CLC
    ADC #1

    CMP #4
    BNE StoreRight

    LDA #0

StoreRight:

    STA Dir

    RTS


; =============================================================================
; ROTAÇÃO ESQUERDA
; =============================================================================

TurnLeft:

    LDA Dir

    BEQ LeftWrap

    SEC
    SBC #1

    STA Dir

    RTS


LeftWrap:

    LDA #3
    STA Dir

    RTS


; =============================================================================
; MOVIMENTO PARA FRENTE
; =============================================================================

MoveForward:

    ; -------------------------------------------------------------------------
    ; Copia posição atual
    ; -------------------------------------------------------------------------

    LDA PosX
    STA TempX

    LDA PosY
    STA TempY


    ; -------------------------------------------------------------------------
    ; Norte
    ; -------------------------------------------------------------------------

    LDA Dir

    CMP #0
    BNE MoveRight

    LDA TempY

    BEQ MovementBlocked

    DEC TempY

    JMP TestMovement


; =============================================================================
; LESTE
; =============================================================================

MoveRight:

    CMP #1
    BNE MoveDown

    LDA TempX

    CMP #7
    BEQ MovementBlocked

    INC TempX

    JMP TestMovement


; =============================================================================
; SUL
; =============================================================================

MoveDown:

    CMP #2
    BNE MoveLeft

    LDA TempY

    CMP #7
    BEQ MovementBlocked

    INC TempY

    JMP TestMovement


; =============================================================================
; OESTE
; =============================================================================

MoveLeft:

    LDA TempX

    BEQ MovementBlocked

    DEC TempX


; =============================================================================
; TESTA A CÉLULA DO MAPA
; =============================================================================

TestMovement:

    ; -------------------------------------------------------------------------
    ; Obtém linha Y
    ; -------------------------------------------------------------------------

    LDY TempY

    LDA MapData,Y

    ; -------------------------------------------------------------------------
    ; Obtém coluna X
    ; -------------------------------------------------------------------------

    LDX TempX


MovementShift:

    CPX #0
    BEQ MovementBit

    LSR

    DEX

    JMP MovementShift


MovementBit:

    AND #%00000001

    ; 1 = parede
    BNE MovementBlocked


    ; -------------------------------------------------------------------------
    ; Espaço livre
    ; -------------------------------------------------------------------------

    LDA TempX
    STA PosX

    LDA TempY
    STA PosY


MovementBlocked:

    RTS


; =============================================================================
; RAYCAST
;
; Procura uma parede até quatro células à frente.
;
; RayDist:
;
;   0 = nenhuma parede
;   1 = parede a 1 célula
;   2 = parede a 2 células
;   3 = parede a 3 células
;   4 = parede a 4 células
; =============================================================================

CastRay:

    ; -------------------------------------------------------------------------
    ; Inicialização
    ; -------------------------------------------------------------------------

    LDA #0
    STA RayDist

    STA WallFound

    STA RayStepCount

    LDA PosX
    STA TempX

    LDA PosY
    STA TempY


; =============================================================================
; PRÓXIMO PASSO DO RAYCAST
; =============================================================================

RayNextStep:

    INC RayStepCount

    ; -------------------------------------------------------------------------
    ; Máximo de quatro células
    ; -------------------------------------------------------------------------

    LDA RayStepCount

    CMP #5
    BCS RayNoWall


    ; -------------------------------------------------------------------------
    ; Direção
    ; -------------------------------------------------------------------------

    LDA Dir

    CMP #0
    BNE RayCheckRight

    ; Norte
    DEC TempY

    JMP RayCheckBounds


RayCheckRight:

    CMP #1
    BNE RayCheckDown

    ; Leste
    INC TempX

    JMP RayCheckBounds


RayCheckDown:

    CMP #2
    BNE RayCheckLeft

    ; Sul
    INC TempY

    JMP RayCheckBounds


RayCheckLeft:

    ; Oeste
    DEC TempX


; =============================================================================
; LIMITES DO MAPA
; =============================================================================

RayCheckBounds:

    ; -------------------------------------------------------------------------
    ; X >= 8
    ; -------------------------------------------------------------------------

    LDA TempX

    CMP #8
    BCS RayHitWall


    ; -------------------------------------------------------------------------
    ; Y >= 8
    ; -------------------------------------------------------------------------

    LDA TempY

    CMP #8
    BCS RayHitWall


    ; -------------------------------------------------------------------------
    ; Detecta valores negativos.
    ;
    ; Como a RAM é unsigned, DEC 00 resulta em FF.
    ; Bit 7 ligado indica que saímos do mapa.
    ; -------------------------------------------------------------------------

    LDA TempX

    BMI RayHitWall

    LDA TempY

    BMI RayHitWall


; =============================================================================
; CONSULTA MAPA
; =============================================================================

    LDY TempY

    LDA MapData,Y

    LDX TempX


RayShift:

    CPX #0
    BEQ RayTestBit

    LSR

    DEX

    JMP RayShift


RayTestBit:

    AND #%00000001

    ; 0 = espaço livre
    BEQ RayNextStep


; =============================================================================
; PAREDE ENCONTRADA
; =============================================================================

RayHitWall:

    LDA #1
    STA WallFound

    LDA RayStepCount
    STA RayDist

    RTS


; =============================================================================
; NENHUMA PAREDE
; =============================================================================

RayNoWall:

    LDA #0
    STA RayDist

    RTS


; =============================================================================
; RENDERIZAÇÃO
; =============================================================================

RenderScene:

    ; -------------------------------------------------------------------------
    ; Descobre a distância da parede
    ; -------------------------------------------------------------------------

    JSR CastRay


    ; -------------------------------------------------------------------------
    ; Parede muito próxima
    ;
    ; 20 -> 172
    ; -------------------------------------------------------------------------

    LDA RayDist

    CMP #1
    BEQ WallNear


    ; -------------------------------------------------------------------------
    ; Parede próxima
    ;
    ; 40 -> 152
    ; -------------------------------------------------------------------------

    CMP #2
    BEQ WallMediumNear


    ; -------------------------------------------------------------------------
    ; Parede média
    ;
    ; 64 -> 128
    ; -------------------------------------------------------------------------

    CMP #3
    BEQ WallMedium


    ; -------------------------------------------------------------------------
    ; Parede distante / sem parede
    ;
    ; 80 -> 112
    ; -------------------------------------------------------------------------

    LDA #80
    STA TopLine

    LDA #112
    STA BottomLine

    JMP BeginRender


; =============================================================================
; PAREDE MÉDIA
; =============================================================================

WallMedium:

    LDA #64
    STA TopLine

    LDA #128
    STA BottomLine

    JMP BeginRender


; =============================================================================
; PAREDE PRÓXIMA
; =============================================================================

WallMediumNear:

    LDA #40
    STA TopLine

    LDA #152
    STA BottomLine

    JMP BeginRender


; =============================================================================
; PAREDE MUITO PRÓXIMA
; =============================================================================

WallNear:

    LDA #20
    STA TopLine

    LDA #172
    STA BottomLine


; =============================================================================
; INÍCIO DA ÁREA VISÍVEL
; =============================================================================

BeginRender:

    ; -------------------------------------------------------------------------
    ; Agora sim desligamos VBLANK.
    ; -------------------------------------------------------------------------

    LDA #0
    STA VBLANK


    ; -------------------------------------------------------------------------
    ; Inicializa contador de linhas
    ; -------------------------------------------------------------------------

    LDA #0
    STA LineCounter


; =============================================================================
; 192 LINHAS VISÍVEIS
; =============================================================================

RenderLoop:

    ; Espera o próximo scanline
    STA WSYNC


    ; -------------------------------------------------------------------------
    ; Limpa playfield
    ; -------------------------------------------------------------------------

    LDA #0

    STA PF0
    STA PF1
    STA PF2


    ; -------------------------------------------------------------------------
    ; Verifica se estamos dentro da parede
    ; -------------------------------------------------------------------------

    LDA LineCounter

    CMP TopLine
    BCC RenderNextLine


    LDA BottomLine

    CMP LineCounter
    BCC RenderNextLine


    ; -------------------------------------------------------------------------
    ; Parede
    ; -------------------------------------------------------------------------

    LDA #$F0
    STA PF0

    LDA #$FF
    STA PF1

    LDA #$FF
    STA PF2


; =============================================================================
; PRÓXIMA LINHA
; =============================================================================

RenderNextLine:

    INC LineCounter

    LDA LineCounter

    CMP #192

    BNE RenderLoop


; =============================================================================
; HUD / CORES
; =============================================================================

    ; -------------------------------------------------------------------------
    ; Cor do fundo baseada na posição X
    ; -------------------------------------------------------------------------

    LDA PosX

    ASL
    ASL

    STA COLUBK


    ; -------------------------------------------------------------------------
    ; Cor do playfield baseada na posição Y
    ; -------------------------------------------------------------------------

    LDA PosY

    ASL
    ASL

    ORA #$20

    STA COLUPF


; =============================================================================
; OVERSCAN
; =============================================================================

    LDA #2
    STA VBLANK

    LDX #30


OverscanLoop:

    STA WSYNC

    DEX

    BNE OverscanLoop

    RTS


; =============================================================================
; TIRO
; =============================================================================

FireWeapon:

    ; -------------------------------------------------------------------------
    ; Se já existe som, não reinicia
    ; -------------------------------------------------------------------------

    LDA SoundTimer

    BNE FireAlreadyActive


    ; -------------------------------------------------------------------------
    ; Volume máximo
    ; -------------------------------------------------------------------------

    LDA #15
    STA AUDV0


    ; -------------------------------------------------------------------------
    ; Tipo de som
    ; -------------------------------------------------------------------------

    LDA #3
    STA AUDC0


    ; -------------------------------------------------------------------------
    ; Frequência
    ; -------------------------------------------------------------------------

    LDA #10
    STA AUDF0


    ; -------------------------------------------------------------------------
    ; Duração
    ; -------------------------------------------------------------------------

    LDA #10
    STA SoundTimer


FireAlreadyActive:

    RTS


; =============================================================================
; ATUALIZA ÁUDIO
; =============================================================================

UpdateAudio:

    LDA SoundTimer

    BEQ AudioOff

    DEC SoundTimer

    RTS


AudioOff:

    LDA #0
    STA AUDV0

    RTS


; =============================================================================
; MAPA 8x8
;
; 1 = parede
; 0 = espaço livre
;
;       0 1 2 3 4 5 6 7
;
; 0     █ █ █ █ █ █ █ █
; 1     █ . . . . . . █
; 2     █ . █ . █ . . █
; 3     █ . █ . █ █ . █
; 4     █ . . . . . . █
; 5     █ █ █ █ █ █ █ █
; 6     █ █ █ █ █ █ █ █
; 7     █ █ █ █ █ █ █ █
;
; =============================================================================

MapData:

    .byte %11111111
    .byte %10000001
    .byte %10101001
    .byte %10101101
    .byte %10000001
    .byte %11111111
    .byte %11111111
    .byte %11111111


; =============================================================================
; VETORES DO 6502
; =============================================================================

    ORG $FFFC

    .word Start
    .word Start